//! `.app` bundle assembly (`docs/design/10` §2.5–2.7): layout, Info.plist,
//! launcher stub, `launch.conf`, licensing notices, runtime copy, ad-hoc
//! codesign. Hand-rolled plist XML — no new dependency (design 10 §2.6).

use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Duration;

use super::error::MacAppError;
use super::runtime::Runtime;

/// Layout of one generated bundle.
#[derive(Debug, Clone)]
pub struct Bundle {
    /// `<out>/<display>.app`
    pub root: PathBuf,
    pub contents: PathBuf,
    pub macos: PathBuf,
    pub resources: PathBuf,
    pub prefix: PathBuf,
}

/// Compute all paths for a bundle named `display` under `out_dir`.
pub fn layout(out_dir: &Path, display: &str) -> Bundle {
    let root = out_dir.join(format!("{display}.app"));
    let contents = root.join("Contents");
    let macos = contents.join("MacOS");
    let resources = contents.join("Resources");
    Bundle {
        prefix: resources.join("prefix"),
        root,
        contents,
        macos,
        resources,
    }
}

/// Create the directory skeleton; refuse to clobber an existing bundle.
pub fn create_layout(bundle: &Bundle) -> Result<(), MacAppError> {
    if bundle.root.exists() {
        return Err(MacAppError::BundleExists {
            path: bundle.root.clone(),
        });
    }
    std::fs::create_dir_all(&bundle.macos)?;
    std::fs::create_dir_all(&bundle.resources)?;
    Ok(())
}

/// Escape XML text content / attribute values (the five predefined entities).
fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

/// `Contents/Info.plist` (design 10 §2.6). `min_macos` is omitted when the
/// runtime has no requirement — an absent key is weaker than a wrong one.
pub fn write_info_plist(
    bundle: &Bundle,
    display: &str,
    slug: &str,
    min_macos: Option<&str>,
) -> Result<(), MacAppError> {
    let key = |k: &str| format!("  <key>{k}</key>\n");
    let val = |v: &str| format!("  <string>{}</string>\n", xml_escape(v));
    let mut plist = String::new();
    plist.push_str("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
    plist.push_str(
        "<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n",
    );
    plist.push_str("<plist version=\"1.0\">\n<dict>\n");
    plist.push_str(&key("CFBundleIdentifier"));
    plist.push_str(&val(&format!("com.noosxe.gogo.{slug}")));
    plist.push_str(&key("CFBundleName"));
    plist.push_str(&val(display));
    plist.push_str(&key("CFBundleExecutable"));
    plist.push_str(&val(display));
    plist.push_str(&key("CFBundlePackageType"));
    plist.push_str("  <string>APPL</string>\n");
    plist.push_str(&key("CFBundleShortVersionString"));
    plist.push_str("  <string>1.0.0</string>\n");
    plist.push_str(&key("CFBundleVersion"));
    plist.push_str("  <string>1</string>\n");
    if let Some(min) = min_macos {
        plist.push_str(&key("LSMinimumSystemVersion"));
        plist.push_str(&val(min));
    }
    plist.push_str(&key("NSHighResolutionCapable"));
    plist.push_str("  <true/>\n");
    plist.push_str("</dict>\n</plist>\n");

    std::fs::write(bundle.contents.join("Info.plist"), plist)?;
    Ok(())
}

/// POSIX-quote a value for embedding in `launch.conf` / the launcher script.
fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// `Resources/launch.conf` — paths **relative to the bundle root** the
/// launcher resolves against `$DIR` (design 10 §2.4). Absolute build-time
/// paths broke the moment the bundle was moved (live finding 2026-10-19).
pub fn write_launch_conf(
    bundle: &Bundle,
    wine: &Path,
    game: &Path,
    recipe_env: &str,
    recipe_args: &str,
) -> Result<(), MacAppError> {
    let rel = |p: &Path| -> String {
        p.strip_prefix(&bundle.root)
            .unwrap_or(p)
            .to_string_lossy()
            .into_owned()
    };
    let mut conf = format!(
        "WINE={}\nPREFIX={}\nGAME={}\nFRAMEWORKS=Resources/wine-frameworks\n",
        sh_quote(&rel(wine)),
        sh_quote(&rel(&bundle.prefix)),
        sh_quote(&rel(game)),
    );
    if !recipe_env.is_empty() {
        conf += &format!("RECIPE_ENV={}\n", sh_quote(recipe_env));
    }
    if !recipe_args.is_empty() {
        conf += &format!("RECIPE_ARGS={}\n", sh_quote(recipe_args));
    }
    std::fs::write(bundle.resources.join("launch.conf"), conf)?;
    Ok(())
}

/// `Contents/MacOS/<display>` launcher stub (design 10 §2.5). Resolves its own
/// location at runtime, so the bundle is draggable after conversion.
pub fn write_launcher(bundle: &Bundle, display: &str) -> Result<PathBuf, MacAppError> {
    let path = bundle.macos.join(display);
    let script = r#"#!/bin/bash
# Generated by `gogo mac-app` — launch this game under the bundled Wine.
set -e
DIR="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=launch.conf
source "$DIR/Resources/launch.conf"
export DYLD_FALLBACK_LIBRARY_PATH="$DIR/$FRAMEWORKS:${DYLD_FALLBACK_LIBRARY_PATH:-}"
export WINEPREFIX="$DIR/$PREFIX"
# Recipe launch env/args (design 11): K=V pairs + word-split args.
for pair in ${RECIPE_ENV:-}; do export "${pair%%=*}=${pair#*=}"; done
# Old installers resolve data files relative to the working directory.
cd "$(dirname "$DIR/$GAME")"
exec "$DIR/$WINE" "$DIR/$GAME" ${RECIPE_ARGS:-} "$@"
"#;
    let mut file = std::fs::File::create(&path)?;
    file.write_all(script.as_bytes())?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o755))?;
    }
    Ok(path)
}

/// Licensing notices inside the bundle (design 10 §8): Wine LGPL pointer for
/// every bundle; an extra GPTK EULA warning when the runtime came from a
/// user-supplied GPTK mount.
pub fn write_notices(bundle: &Bundle, runtime: &Runtime) -> Result<(), MacAppError> {
    std::fs::write(
        bundle.resources.join("LICENSE-wine.txt"),
        format!(
            "This application bundles Wine ({}), licensed under the GNU LGPL v2.1.\n\
             Source: https://github.com/wine-mirror/wine\n\
             Wine is copyright the Wine project authors. This bundle was produced by\n\
             `gogo mac-app` on the user's machine from the user's own runtime copy;\n\
             gogo itself ships no Wine binaries.\n",
            runtime.version
        ),
    )?;
    if runtime.mode == super::runtime::RuntimeMode::Gptk {
        std::fs::write(
            bundle.resources.join("README-GPTK.txt"),
            "This application embeds Apple's Game Porting Toolkit Wine runtime.\n\
             Apple's Game Porting Toolkit license applies to that embedded copy;\n\
             it was downloaded by the user from Apple under the user's own terms.\n\
             Redistributing this bundle embeds Apple-licensed software — do so at\n\
             your own risk. gogo never downloads or ships the GPTK itself.\n",
        )?;
    }
    Ok(())
}

/// `Resources/runtime.txt` — which runtime was used, for support honesty
/// (design 10 §3).
pub fn write_runtime_marker(bundle: &Bundle, runtime: &Runtime) -> Result<(), MacAppError> {
    std::fs::write(
        bundle.resources.join("runtime.txt"),
        format!(
            "kind={}\nversion={}\nsource={}\n",
            runtime.mode.as_str(),
            runtime.version,
            runtime.wine.display()
        ),
    )?;
    Ok(())
}

/// Copy the runtime tree into `Resources/wine` — the self-contained price
/// (hundreds of MB, docs/13 §4). Returns the copied byte total.
pub fn copy_runtime(runtime: &Runtime, dest: &Path) -> Result<u64, MacAppError> {
    let bytes = copy_tree(&runtime.root, dest)?;
    // Post-copy validation: a bundle whose launcher cannot exec its wine is
    // dead on arrival (live finding 2026-10-19 — symlinked wine binaries were
    // silently skipped and the bundle reported success).
    let wine = dest.join(
        runtime
            .wine
            .strip_prefix(&runtime.root)
            .unwrap_or_else(|_| Path::new("bin/wine")),
    );
    if !wine.is_file() {
        return Err(MacAppError::RuntimeInvalid {
            path: dest.to_path_buf(),
            reason: format!("wine binary missing after runtime copy: {}", wine.display()),
        });
    }
    Ok(bytes)
}

/// Runtimes that live inside a `.app` (Wineskin/CX wrappers) link their wine
/// binaries against dylibs in the wrapper's `Contents/Frameworks`. Copy the
/// top-level `.dylib` files into `Resources/wine-frameworks` so the launcher
/// can point `DYLD_FALLBACK_LIBRARY_PATH` at them (live finding 2026-10-19:
/// `Library not loaded: @rpath/libinotify.0.dylib` on first launch).
pub fn copy_runtime_dylibs(runtime: &Runtime, dest: &Path) -> Result<Option<u64>, MacAppError> {
    let mut anc = runtime.root.parent();
    let frameworks = loop {
        match anc {
            Some(dir) => {
                if dir.ends_with("Contents") {
                    break dir.join("Frameworks");
                }
                anc = dir.parent();
            }
            None => return Ok(None),
        }
    };
    if !frameworks.is_dir() {
        return Ok(None);
    }
    std::fs::create_dir_all(dest)?;
    let mut total = 0u64;
    for entry in std::fs::read_dir(&frameworks)? {
        let entry = entry?;
        let path = entry.path();
        if path.extension().is_some_and(|e| e == "dylib") && path.is_file() {
            total += std::fs::metadata(&path)?.len();
            std::fs::copy(&path, dest.join(entry.file_name()))?;
        }
    }
    Ok(Some(total))
}

fn copy_tree(src: &Path, dest: &Path) -> Result<u64, MacAppError> {
    let mut total = 0u64;
    std::fs::create_dir_all(dest)?;
    for entry in std::fs::read_dir(src)? {
        let entry = entry?;
        let ty = entry.file_type()?;
        let to = dest.join(entry.file_name());
        if ty.is_dir() {
            total += copy_tree(&entry.path(), &to)?;
        } else if ty.is_symlink() {
            // Skip symlinks: nothing inside a Wine tree needs them in a bundle,
            // and replicating targets could pull in paths outside `root`.
            continue;
        } else {
            let bytes = entry.metadata()?.len();
            std::fs::copy(entry.path(), &to)?;
            total += bytes;
        }
    }
    Ok(total)
}

/// Ad-hoc codesign argv (`codesign --force --deep --sign - <bundle>`) — split
/// out for unit testing; [`codesign_adhoc`] executes + verifies.
pub fn codesign_argv(bundle: &Path) -> Vec<std::ffi::OsString> {
    vec![
        "codesign".into(),
        "--force".into(),
        "--deep".into(),
        "--sign".into(),
        "-".into(),
        bundle.as_os_str().to_os_string(),
    ]
}

/// Codesign behavior for one conversion (design 10 §2.7). macOS-only tooling:
/// tests (and non-mac hosts) use [`CodesignPolicy::Skip`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CodesignPolicy {
    /// `codesign --force --deep --sign -` + `--verify`.
    Adhoc,
    /// Test/dry mode: no codesign call at all.
    Skip,
}

pub fn codesign_adhoc(bundle: &Path, policy: CodesignPolicy) -> Result<(), MacAppError> {
    if policy == CodesignPolicy::Skip {
        return Ok(());
    }
    let args = codesign_argv(bundle);
    let out = std::process::Command::new(&args[0])
        .args(&args[1..])
        .output()
        .map_err(|e| MacAppError::Codesign {
            stderr: format!("cannot execute codesign: {e}"),
        })?;
    if !out.status.success() {
        return Err(MacAppError::Codesign {
            stderr: String::from_utf8_lossy(&out.stderr).trim().to_string(),
        });
    }
    let verify = std::process::Command::new("codesign")
        .arg("--verify")
        .arg(bundle)
        .output()
        .map_err(|e| MacAppError::Codesign {
            stderr: format!("cannot execute codesign: {e}"),
        })?;
    if !verify.status.success() {
        return Err(MacAppError::Codesign {
            stderr: String::from_utf8_lossy(&verify.stderr).trim().to_string(),
        });
    }
    Ok(())
}

/// Strip macOS metadata "detritus" (resource forks, FinderInfo, provenance,
/// quarantine) from every file in the bundle — `codesign` refuses to seal a
/// bundle whose files carry them (live finding 2026-10-18, GPTK runtime files
/// copied from a quarantined app). No-op when codesign is skipped. Best-effort
/// on hosts without `/usr/bin/xattr` (non-mac).
pub fn strip_detritus(bundle: &Path, policy: CodesignPolicy) -> Result<(), MacAppError> {
    if policy == CodesignPolicy::Skip || !Path::new("/usr/bin/xattr").exists() {
        return Ok(());
    }
    // Delete only the seal-breaking classes. NOT `xattr -cr`: it also targets
    // SIP-protected com.apple.provenance, which cannot be removed (exit 1) and
    // which codesign tolerates anyway (live finding 2026-10-18, third run).
    for attr in [
        "com.apple.FinderInfo",
        "com.apple.ResourceFork",
        "com.apple.quarantine",
    ] {
        let status = super::installer::run_with_timeout(
            Command::new("/usr/bin/xattr")
                .args(["-dr", attr])
                .arg(bundle),
            Duration::from_secs(120),
        );
        if status.is_none() {
            return Err(MacAppError::Codesign {
                stderr: format!("xattr -dr {attr} timed out — bundle metadata not cleared"),
            });
        }
    }
    Ok(())
}

